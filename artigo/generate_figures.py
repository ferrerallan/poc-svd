def layer_image(U, S, Vt, i):
    """
    * what? - Returns layer i of the SVD of the photo as an image array centered on mid gray.
    * why?  - A layer has negative and positive values; centering on 128 makes it viewable.
    * how?  - S[i] * outer(U[:, i], Vt[i]) rescaled by its largest absolute value.
    """
    #region 1 - Build and rescale the layer
    # what? - Returns values around 128.
    # how?  - Same display rule as to_visible_image in experiment 0.
    c = S[i] * np.outer(U[:, i], Vt[i])
    return 128 + 127 * c / np.abs(c).max()
    #endregion


def partial_sum(U, S, Vt, n):
    """
    * what? - Returns the sum of the first n SVD layers, clipped to the 0-255 range.
    * why?  - It is the reconstruction of the photo with n layers.
    * how?  - (U[:, :n] * S[:n]) @ Vt[:n].
    """
    #region 1 - Add the first n layers
    # what? - Returns the reconstruction.
    # how?  - np.clip keeps pixel values valid.
    return np.clip((U[:, :n] * S[:n]) @ Vt[:n], 0, 255)
    #endregion


def figure_02_svd_layers():
    """
    * what? - Draws figure 2: four SVD layers of the photo and the sums of the first N layers.
    * why?  - Shows that each layer alone is a stripe pattern and that a few layers already rebuild the photo.
    * how?  - SVD of the grayscale photo; top row shows layers 1, 2, 5 and 35; bottom row the sums with 1, 3, 10 and 35 layers.
    """
    #region 1 - Decompose the photo
    # what? - Grayscale matrix, its SVD and the total energy.
    # how?  - total_energy is the sum of the squared singular values.
    g = np.asarray(PHOTO.convert("L"), float)
    U, S, Vt = np.linalg.svd(g, full_matrices=False)
    total_energy = (S ** 2).sum()
    fig, axs = plt.subplots(2, 5, figsize=(15, 6.6))
    #endregion

    #region 2 - Draw the original and the single layers
    # what? - First row: the photo and four layers with their weights.
    # how?  - Weights are printed with a dot as the thousands separator.
    axs[0, 0].imshow(g, cmap="gray", vmin=0, vmax=255)
    axs[0, 0].set_title("a foto original", fontsize=12)
    for k, i in enumerate((0, 1, 4, 34), start=1):
        axs[0, k].imshow(np.clip(layer_image(U, S, Vt, i), 0, 255), cmap="gray", vmin=0, vmax=255)
        axs[0, k].set_title(f"camada {i + 1}\npeso σ = {S[i]:,.0f}".replace(",", "."), fontsize=11)
    #endregion

    #region 3 - Draw the partial sums
    # what? - Second row: the sum of the first N layers with the energy and the share of numbers kept.
    # how?  - Each layer costs height + width + 1 numbers.
    axs[1, 0].axis("off")
    axs[1, 0].text(0.5, 0.5, "somando as\nprimeiras N\ncamadas:", ha="center", va="center", fontsize=14, fontweight="bold")
    for k, n in enumerate((1, 3, 10, 35), start=1):
        e = 100 * (S[:n] ** 2).sum() / total_energy
        n_numbers = n * (g.shape[0] + g.shape[1] + 1)
        axs[1, k].imshow(partial_sum(U, S, Vt, n), cmap="gray", vmin=0, vmax=255)
        axs[1, k].set_title(f"N = {n}\n{e:.1f}% da energia · {100 * n_numbers / g.size:.1f}% dos números", fontsize=10.5)
    #endregion

    #region 4 - Finish and save
    # what? - Removes the ticks, adds the title and saves.
    # how?  - h_pad leaves room between the two rows for the two-line titles.
    for a in axs.ravel():
        a.set_xticks([])
        a.set_yticks([])
    fig.suptitle("A SVD quebra a foto em camadas ordenadas por peso (σ). Cada camada sozinha parece um padrão de listras; a soma vira foto.", fontsize=13, y=0.99)
    fig.tight_layout(rect=[0, 0, 1, 0.95], h_pad=3.0)
    save_figure(fig, "02_svd_camadas.png")
    #endregion


def figure_03_svd_geometry():
    """
    * what? - Draws figure 3: a 2-D matrix turns a circle into an ellipse; changing sigma stretches it, changing U turns it.
    * why?  - Gives the geometric meaning of the thesis question: weights (sigma) versus directions (U).
    * how?  - Three panels share V0; the middle one scales sigma 1, the right one rotates U by 25 degrees; arrows show the axes.
    """
    #region 1 - Set up the matrices and the three cases
    # what? - Rotation helper, W0 = U0 diag(s0) V0' and the three cases to draw.
    # how?  - A lambda builds W from any U and sigma with the same V0.
    th = np.linspace(0, 2 * np.pi, 400); circ = np.vstack([np.cos(th), np.sin(th)])
    rotation = lambda a: np.array([[np.cos(a), -np.sin(a)], [np.sin(a), np.cos(a)]])
    U0, V0, s0 = rotation(np.deg2rad(30)), rotation(np.deg2rad(-20)), np.array([2.0, 0.8])
    W = lambda U, s: U @ np.diag(s) @ V0.T
    cases = [("W0: matriz original", U0, s0, None), ("Mudou o PESO σ\n(mesmas direções, eixo 1 mais longo)", U0, np.array([2.8, 0.8]), "σ"),
             ("Mudou a DIREÇÃO U\n(mesmos pesos, eixos girados 25°)", rotation(np.deg2rad(25)) @ U0, s0, "U")]
    #endregion

    #region 2 - Draw each case and save
    # what? - Circle, deformed ellipse, reference ellipse and the labeled axes per panel.
    # how?  - The reference ellipse (dotted) appears in the two changed panels.
    fig, axs = plt.subplots(1, 3, figsize=(15, 5.3))
    for ax, (title, U, s, kind) in zip(axs, cases):
        ax.plot(*circ, color="#bbbbbb", lw=1.5, ls="--", label="círculo de entrada")
        ellipse = W(U, s) @ circ; ax.plot(*ellipse, color=PURPLE, lw=3, label="como a matriz o deforma")
        if kind is not None:
            ax.plot(*(W(U0, s0) @ circ), color=GRAY, lw=1.5, ls=":", label="W0 (referência)")
        for i, color in enumerate((ORANGE, BLUE)):
            u = U[:, i] * s[i]; ax.add_patch(FancyArrowPatch((0, 0), tuple(u), arrowstyle="-|>", mutation_scale=22, color=color, lw=3))
            ax.text(*(u * 1.25 + np.array([0.0, 0.18 if i == 0 else 0.0])), f"σ{i + 1}={s[i]:.1f}", color=color, fontsize=12, fontweight="bold", ha="center", va="center", bbox=dict(fc="white", ec="none", pad=1.5))
        ax.set_xlim(-3.3, 3.3); ax.set_ylim(-3.3, 3.3); ax.set_aspect("equal"); ax.axhline(0, color="#dddddd", lw=1); ax.axvline(0, color="#dddddd", lw=1)
        ax.set_title(title, fontsize=13, color=TEXT_COLOR); ax.set_xticks([]); ax.set_yticks([])
    axs[0].legend(loc="lower left", fontsize=9.5, frameon=False)
    fig.suptitle("A SVD em 2D: a matriz transforma um círculo em uma elipse. O comprimento de cada eixo é o peso σ; a direção do eixo é o vetor singular.", fontsize=13, y=1.02)
    fig.tight_layout(); save_figure(fig, "03_svd_geometria.png")
    #endregion


