def box(ax, x, y, w, h, text, fc=GRAY_L, ec=GRAY, fs=13, bold=False, tc=TEXT_COLOR, r=0.02, lw=1.6, ls="-"):
    """
    * what? - Draws a rounded box with centered text on an axis.
    * why?  - Almost every diagram of the article is made of labeled boxes.
    * how?  - A FancyBboxPatch plus an ax.text at the center of the box.
    """
    #region 1 - Draw the box and its text
    # what? - Adds the patch and the label.
    # how?  - r is the corner rounding in data units; bold switches the font weight.
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle=f"round,pad=0,rounding_size={r}", fc=fc, ec=ec, lw=lw, ls=ls))
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=fs, color=tc, fontweight="bold" if bold else "normal", linespacing=1.35)
    #endregion


def arrow(ax, p, q, color=GRAY, lw=2, ms=18, style="-|>", rad=0.0):
    """
    * what? - Draws an arrow from point p to point q on an axis.
    * why?  - Diagrams use arrows to show the flow of data.
    * how?  - A FancyArrowPatch with zero shrink at both ends.
    """
    #region 1 - Draw the arrow
    # what? - Adds the patch.
    # how?  - rad bends the arrow; ms is the head size.
    ax.add_patch(FancyArrowPatch(p, q, arrowstyle=style, mutation_scale=ms, color=color, lw=lw, connectionstyle=f"arc3,rad={rad}", shrinkA=0, shrinkB=0))
    #endregion


def new_canvas(w, h):
    """
    * what? - Creates a figure whose single axis has data coordinates equal to its size in inches and no frame.
    * why?  - Diagrams are laid out in free coordinates, not on a chart.
    * how?  - plt.subplots with the given size; limits (0, w) and (0, h); axis off.
    """
    #region 1 - Create the canvas
    # what? - Returns the figure and the axis.
    # how?  - The same limits as the size make 1 unit equal 1 inch.
    fig, ax = plt.subplots(figsize=(w, h))
    ax.set_xlim(0, w)
    ax.set_ylim(0, h)
    ax.axis("off")
    return fig, ax
    #endregion


def save_figure(fig, name):
    """
    * what? - Saves a figure into artigo/images and closes it.
    * why?  - Every figure is saved with the same resolution and margins.
    * how?  - dpi 130, tight bounding box with 0.25 inch padding, then plt.close.
    """
    #region 1 - Save and close
    # what? - Writes the PNG and frees the figure.
    # how?  - Prints the file name as a progress line.
    fig.savefig(OUT_DIR / name, dpi=130, bbox_inches="tight", pad_inches=0.25)
    plt.close(fig)
    print("ok", name)
    #endregion


