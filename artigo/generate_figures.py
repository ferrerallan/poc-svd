def fmt_number(v):
    """
    * what? - Formats a number the way the article prints it: integers bare, others with two decimals and a comma.
    * why?  - The 2 x 2 example mixes 4, 2 and 0.71; the figures must print 4 (not 4,00) and 0,71 (not 0.71).
    * how?  - Rounds to 6 places first so 3.9999999 counts as an integer, then formats.
    """
    #region 1 - Format
    # what? - Returns the label string.
    # how?  - float.is_integer decides between the two formats.
    v = round(float(v), 6)
    return f"{int(v)}" if v.is_integer() else f"{v:.2f}".replace(".", ",")
    #endregion


def table_2x2(ax, x, y, cells, highlight=None, cell=0.7, fs=13.5):
    """
    * what? - Draws a 2 x 2 table of numbers at (x, y) with optional per-cell background colors.
    * why?  - Figure 15 shows the SVD of a 2 x 2 example as real tables, so the same drawing is repeated eight times.
    * how?  - One Rectangle and one text per cell; numbers print the Brazilian way (comma decimal); returns the table width.
    """
    #region 1 - Draw the four cells
    # what? - Row r, column c of the grid, top row first.
    # how?  - highlight maps (r, c) to a fill color; fmt_number prints the value.
    for r in range(2):
        for c in range(2):
            fc = (highlight or {}).get((r, c), "white")
            ax.add_patch(Rectangle((x + c * cell, y + (1 - r) * cell), cell, cell, fc=fc, ec=GRAY, lw=1.4))
            ax.text(x + c * cell + cell / 2, y + (1 - r) * cell + cell / 2, fmt_number(cells[r][c]), ha="center", va="center", fontsize=fs, color=TEXT_COLOR)
    return 2 * cell
    #endregion


