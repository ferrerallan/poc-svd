def number_table(ax, x, y, rows, color, cw=0.62, ch=0.52, fs=13):
    """
    * what? - Draws a small table of integers at (x, y), top row first, every cell filled with the given color.
    * why?  - The MLP example of figure 21 is made of six such tables (token, fc1, answers, filtered answers, fc2, result).
    * how?  - One Rectangle and one text per cell; returns the table width and height.
    """
    #region 1 - Draw the cells
    # what? - Grid of len(rows) x len(rows[0]) cells.
    # how?  - Row 0 is drawn on top; negative numbers keep their sign in the label.
    n_rows, n_cols = len(rows), len(rows[0])
    for r, row in enumerate(rows):
        for c, v in enumerate(row):
            ax.add_patch(Rectangle((x + c * cw, y + (n_rows - 1 - r) * ch), cw, ch, fc=color, ec=GRAY, lw=1.3))
            ax.text(x + c * cw + cw / 2, y + (n_rows - 1 - r) * ch + ch / 2, fmt_number(v), ha="center", va="center", fontsize=fs, color=TEXT_COLOR)
    return n_cols * cw, n_rows * ch
    #endregion


