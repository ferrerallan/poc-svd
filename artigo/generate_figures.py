def figure_22_mlp_filter():
    """
    * what? - Draws figure 22: why the filter matters, with the absolute-value test: one table alone is a straight line through zero; expand, filter and sum make the V.
    * why?  - Without the filter, fc1 and fc2 collapse into one table; the picture shows what one table can and cannot do.
    * how?  - Two plots of output against input: lines a*x on the left, |x| on the right, with the two target points (3, 3) and (-3, 3).
    """
    #region 1 - Draw the two plots
    # what? - Left: several straight lines through the origin; right: the V shape of |x|; both with the target points.
    # how?  - The target points are the two rows of table 3; the right plot's caption spells the three steps for x = 3.
    fig, axs = plt.subplots(1, 2, figsize=(13, 5.2))
    xs = np.linspace(-4, 4, 200)
    for ax in axs:
        ax.axhline(0, color="#dddddd", lw=1); ax.axvline(0, color="#dddddd", lw=1)
        ax.set_xlim(-4, 4); ax.set_ylim(-4, 4); ax.set_aspect("equal"); ax.set_xlabel("x (o que entra)", fontsize=11); ax.set_ylabel("saída", fontsize=11)
        ax.plot([3, -3], [3, 3], "o", color=RED, ms=9, zorder=5)
        ax.text(3, 3.35, "x = 3 → 3", ha="center", va="bottom", fontsize=10.5, color=RED); ax.text(-3, 3.35, "x = -3 → 3", ha="center", va="bottom", fontsize=10.5, color=RED)
    for a, (lx, ly) in ((1.0, (1.6, 2.1)), (-1.0, (1.6, -2.1)), (0.5, (2.6, 0.9))):
        axs[0].plot(xs, a * xs, color=GRAY, lw=2, alpha=0.8)
        axs[0].text(lx, ly, f"a = {fmt_number(a)}", ha="center", va="center", fontsize=10, color=GRAY, bbox=dict(fc="white", ec="none", pad=1.5))
    axs[0].set_title("uma tabela só: saída = a × x\nnenhuma reta passa pelos dois pontos", fontsize=12.5, color=TEXT_COLOR)
    axs[1].plot(xs, np.abs(xs), color=GREEN, lw=3)
    axs[1].set_title("expandir [x, -x], filtrar, somar: saída = |x|\npassa pelos dois pontos", fontsize=12.5, color=GREEN)
    axs[1].text(0, -2.2, "x = 3: [3, -3] → filtro → [3, 0] → soma → 3\nx = -3: [-3, 3] → filtro → [0, 3] → soma → 3", ha="center", va="center", fontsize=10.5, color=TEXT_COLOR, linespacing=1.5, bbox=dict(fc="white", ec=GRAY_L, pad=4))
    fig.suptitle("Sem o filtro, fc1 e fc2 em sequência valem uma tabela só, e uma tabela só é uma reta pelo zero.", fontsize=12.5, y=0.02)
    fig.tight_layout(rect=[0, 0.06, 1, 1]); save_figure(fig, "27_sem_filtro_uma_tabela_so.png")
    #endregion


