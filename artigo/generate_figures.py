def multiplication_table(ax, x, y, sigma, u, v, color, cw=2.0, ch=0.95, hw=0.8, hh=0.62):
    """
    * what? - Draws one layer of the 2 x 2 example as a multiplication table: column of U on the left, row of Vt on top.
    * why?  - Shows what a column of U and a row of Vt are: the headers of a multiplication table that the sigma scales.
    * how?  - Colored header cells hold u and v; each inner cell prints sigma x u[r] x v[c] and its result.
    """
    #region 1 - Draw the two headers
    # what? - Row header (the column of U, one cell per row) and column header (the row of Vt, one cell per column).
    # how?  - The headers share the layer's color; the corner shows the sigma.
    ax.text(x + hw / 2, y + 2 * ch + hh / 2, f"σ = {fmt_number(sigma)}", ha="center", va="center", fontsize=13, fontweight="bold", color=TEXT_COLOR)
    for r in range(2):
        ax.add_patch(Rectangle((x, y + (1 - r) * ch), hw, ch, fc=color, ec=GRAY, lw=1.4))
        ax.text(x + hw / 2, y + (1 - r) * ch + ch / 2, fmt_number(u[r]), ha="center", va="center", fontsize=13.5, color=TEXT_COLOR)
    for c in range(2):
        ax.add_patch(Rectangle((x + hw + c * cw, y + 2 * ch), cw, hh, fc=color, ec=GRAY, lw=1.4))
        ax.text(x + hw + c * cw + cw / 2, y + 2 * ch + hh / 2, fmt_number(v[c]), ha="center", va="center", fontsize=13.5, color=TEXT_COLOR)
    #endregion

    #region 2 - Fill the inner cells with the arithmetic
    # what? - Each cell: sigma x (its row header) x (its column header) = value.
    # how?  - Two lines of text per cell; the product is computed, not typed.
    for r in range(2):
        for c in range(2):
            ax.add_patch(Rectangle((x + hw + c * cw, y + (1 - r) * ch), cw, ch, fc="white", ec=GRAY, lw=1.4))
            value = sigma * u[r] * v[c]
            ax.text(x + hw + c * cw + cw / 2, y + (1 - r) * ch + ch / 2 + 0.17, f"{fmt_number(sigma)} × {fmt_number(u[r])} × {fmt_number(v[c])}", ha="center", va="center", fontsize=10, color=GRAY)
            ax.text(x + hw + c * cw + cw / 2, y + (1 - r) * ch + ch / 2 - 0.2, f"= {fmt_number(value)}", ha="center", va="center", fontsize=14, fontweight="bold", color=TEXT_COLOR)
    #endregion


